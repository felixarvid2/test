// Regenerates js/samples.js from samples/<lab>/*.txt so the example labs also work when
// index.html is opened directly from disk (file:// cannot fetch the .txt files).
// Usage: node tools/build-samples.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'samples');
const LABS = {
  branch: { title: 'Branch office', text: 'Router-on-a-stick, NAT, DHCP and OSPF between two routers, one access switch.' },
  campus: { title: 'Campus', text: 'Layer-3 switch, EIGRP, serial PPP WAN, GRE tunnel, DHCP snooping and DAI on the access switch.' }
};
const labs = fs.readdirSync(dir).filter(d => fs.statSync(path.join(dir, d)).isDirectory()).sort().map(d => ({
  id: d, title: (LABS[d] || {}).title || d, text: (LABS[d] || {}).text || '',
  files: fs.readdirSync(path.join(dir, d)).filter(f => f.endsWith('.txt')).sort().map(f => ({ name: f, text: fs.readFileSync(path.join(dir, d, f), 'utf8') }))
}));
const out = '// Generated by tools/build-samples.js – do not edit by hand.\n' +
  '(function (root) {\n  const CCA = root.CCA = root.CCA || {};\n  CCA.labs = ' + JSON.stringify(labs, null, 2) + ';\n' +
  '  CCA.samples = CCA.labs[0].files;\n' +
  '  if (typeof module !== \'undefined\' && module.exports) module.exports = CCA;\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'samples.js'), out);
console.log('Wrote js/samples.js with ' + labs.length + ' lab(s): ' + labs.map(l => l.id + ' (' + l.files.length + ')').join(', '));
